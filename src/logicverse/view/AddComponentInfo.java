    public AddComponentInfo(java.awt.Frame parent, Circuit circuit, JPanel jpanel, String componentName, boolean modal) {
        super(parent, modal);
        initComponents();
        this.jpanel = jpanel;
        this.component = null;
        setTitle("Add " + componentName + " Component");
        // MINIX
        System.out.println("Component Name = " + component);
        switch(componentName) {
            case "AND":
                component = new JEAND();
                break;
            case "OR":
                component = new JEOR();
                break;
            case "NOT":
                component = new JENOT();
                break;
            case "Binary Probe":
                component = new JEProbe();
                break;
            case "Binary Switch":
                component = new JESwitch();
                break;
            default:
                break;
        }
        this.circuit = circuit;
        CompName.setText(this.component.component.getName());
    }

