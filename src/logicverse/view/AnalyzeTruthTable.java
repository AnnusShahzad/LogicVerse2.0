    private class TruthTable extends AbstractTableModel {
        Circuit circuit;
        List<Component> switches;
        List<Point> outputPoints;
        ArrayList<ArrayList<String>> mat;
        
        public TruthTable(Circuit circuit) {
            this.circuit = circuit;
            this.mat = new ArrayList<>();
            switches = circuit.getComponents().stream().filter(it -> it instanceof Switch).toList();
            outputPoints = circuit.getComponents().stream().map(it -> ((AbstractComponent)it).Outputs).flatMap(List::stream).toList();

            int colCount = getColumnCount();
            int rowCount = getRowCount();
            // Filling Data
            for(int i = 0; i < rowCount; i++) {
                ArrayList<String> t = new ArrayList<>();
                int full = rowCount;
                
                // Doing Click Operations
                for(int j = 0; j < switches.size(); j++) {
                    int half = full >> 1;
                    boolean exp = ((i % full) >= half);
                    Switch s = (Switch)switches.get(j);
                    if(s.getState() != exp)
                        s.click();
                    full = half;
                }
                
//                // Doing Execute Operations just to be Safe
                for(int j = 0; j < switches.size(); j++) {
                    Switch s = (Switch)switches.get(j);
                    s.execute();
                }
                
                // Saving to t
                for(int j = 0; j < colCount; j++) {
                    t.add(String.valueOf(outputPoints.get(j).get()?1:0));
                }
                mat.add(t);
            }
        }
        
        public String getColumnName(int col) {
            return outputPoints.get(col).toString();
        }
        
        public int getColumnCount() {
            return outputPoints.size();
        }
        public int getRowCount() {
            return 1 << switches.size();
        }
        public Object getValueAt(int i, int j) {
            return mat.get(i).get(j);
        }
    }
